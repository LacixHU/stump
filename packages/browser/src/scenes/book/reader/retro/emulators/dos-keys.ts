const LETTERS = 'abcdefghijklmnopqrstuvwxyz'
for (const letter of LETTERS) {
	OVERLAY_TO_CODE[letter as OverlayKeyId] = letter.toUpperCase().charCodeAt(0)
}
for (let digit = 0; digit <= 9; digit += 1) {
	OVERLAY_TO_CODE[String(digit) as OverlayKeyId] = 48 + digit
}

export function overlayKeyCode(id: OverlayKeyId): number | null {
	return OVERLAY_TO_CODE[id] ?? null
}

export function dispatchableKeyCode(target: Dispatchable): number | null {
	if (typeof target === 'string') return overlayKeyCode(target)
	return DOS_KEY_CODES[target.code] ?? null
}

export function swallowDosKeyRepeat(event: KeyboardEvent): void {
	if (!event.repeat) return
	event.preventDefault()
	event.stopImmediatePropagation()
}
